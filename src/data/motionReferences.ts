export function getExerciseMotionReference(exerciseId: string): ExerciseMotionReference | null {
  return byExerciseId.get(exerciseId) ?? null;
}

export function getMotionPrototype(id: string): MotionPrototypeReference | null {
  return MOTION_PROTOTYPES.find((clip) => clip.id === id) ?? null;
}

export function isMotionPrototypeId(id: string): id is MotionPrototypeId {
  return getMotionPrototype(id) !== null;
}
