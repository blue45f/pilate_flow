const sourceBySlug = new Map(sourceLedger.map((source) => [source.sourceSlug, source]));

const expandedSourceByExerciseId = new Map<string, (typeof sourceLedger)[number]>(
  EXPANDED_MOVEMENT_SEEDS.flatMap((seed) => {
    const source = sourceBySlug.get(seed.sourceSlug);
    return source ? [[`expanded-${seed.apparatus}-${seed.slug}`, source] as const] : [];
  }),
);

/** A changed local video/apparatus must not inherit the checked source binding. */
export function getExpandedMovementSource(
  exerciseOrId: string | Pick<PilatesExercise, 'id' | 'apparatus' | 'youtube'>,
) {
  const source = expandedSourceByExerciseId.get(
    typeof exerciseOrId === 'string' ? exerciseOrId : exerciseOrId.id,
  );
  if (!source || typeof exerciseOrId === 'string') return source;
  return source.apparatus === exerciseOrId.apparatus &&
    source.videoId === exerciseOrId.youtube.videoId &&
    exerciseOrId.youtube.url === `https://www.youtube.com/watch?v=${source.videoId}`
    ? source
    : undefined;
}

