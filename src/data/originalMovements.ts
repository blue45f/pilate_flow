function createOriginalMovement(apparatus: ApparatusType, plan: MovementPlan): PilatesExercise {
  return attachExistingVideoReference({
    id: `original-${apparatus}-${plan.slug}`,
    nameKo: plan.ko,
    nameEn: plan.en,
    apparatus,
    requiredEquipment: [apparatus === 'barrel' ? 'ladder-barrel' : apparatus],
    props: plan.props ?? ['none'],
    blockCategory: plan.block,
    spinalPlanes: plan.planes ?? ['neutral'],
    bodyPosition: plan.position,
    level: plan.level ?? '1.0',
    defaultDurationMin: plan.minutes ?? 4,
    isUnilateral: plan.unilateral ?? false,
    springs:
      apparatus === 'mat' || apparatus === 'barrel' ? '스프링 사용 없음' : '강사가 기구별 설정',
    box: plan.box ?? 'none',
    footbar: apparatus === 'reformer' ? 'mid' : 'none',
    headrest: 'flat',
    targetMuscles: plan.focus,
    breathPattern: '편안한 호흡을 이어가며 힘을 쓰는 구간의 호흡은 강사와 조정합니다.',
    cues: [plan.cue, '높이와 횟수보다 편안한 범위와 일정한 속도를 먼저 확인합니다.'],
    precautions: `강사 검토 전 계획 자료입니다. ${apparatusChecks[apparatus]} ${plan.check ?? '통증이나 불편이 생기면 동작을 멈추고 강사와 구성을 조정합니다.'}`,
    layers: {
      easy: plan.easier ?? '지지를 더하고 움직임의 범위를 줄여 준비 동작을 연습합니다.',
      standard: plan.cue,
      hard: plan.harder ?? '강사가 확인한 범위에서 속도 또는 유지 시간을 조정합니다.',
    },
    youtube: {
      videoId: '',
      channelName: '직접 작성한 계획 자료',
      videoTitle: '',
      startSec: 0,
      url: '',
      note: '원본 영상 출처 없음 · 앱을 위해 직접 작성한 계획 메타데이터 · 강사 검토 필요',
    },
    favoriteTag: 'none',
    tempo: 'slow-precise',
  });
}

// Alternate apparatus families so the initial browse view shows the breadth of the library.
const browseOrder: ApparatusType[] = ['reformer', 'mat', 'cadillac', 'chair', 'barrel'];
export const ORIGINAL_MOVEMENTS: PilatesExercise[] = Array.from(
  { length: Math.max(...browseOrder.map((apparatus) => plans[apparatus].length)) },
  (_, index) =>
    browseOrder.flatMap((apparatus) => {
      const plan = plans[apparatus][index];
      return plan ? [createOriginalMovement(apparatus, plan)] : [];
    }),
).flat();
