#!/usr/bin/env python3
"""
Generates broadcast-mastered Korean Studio Neural AI Voice MP3s (`ko-KR-SunHiNeural`)
for all 524 canonical Pilates archetypes + reusable studio coaching clips,
and emits `src/data/studioNeuralVoiceManifest.ts`.
"""
from __future__ import annotations

import asyncio
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import edge_tts

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS_JSON = ROOT / "scripts" / ".studio-voice-scripts.json"
OUT_EX_DIR = ROOT / "public" / "audio" / "studio-voice" / "ex"
OUT_CLIPS_DIR = ROOT / "public" / "audio" / "studio-voice" / "clips"
MANIFEST_TS = ROOT / "src" / "data" / "studioNeuralVoiceManifest.ts"

VOICE_ID = "ko-KR-SunHiNeural"
VOICE_RATE = "-4%"
VOICE_PITCH = "+0Hz"
CONCURRENCY = 12

# Warm studio mentor broadcast vocal EQ + EBU R128 loudness normalization (-16 LUFS), 24kHz mono 28kbps MP3
FFMPEG_FILTER = (
    "highpass=f=85,"
    "equalizer=f=210:t=q:w=1.2:g=1.6,"
    "equalizer=f=3100:t=q:w=1.3:g=1.4,"
    "loudnorm=I=-16:TP=-1.5:LRA=11"
)


def master_mp3(raw_path: Path, out_path: Path) -> bool:
    cmd = [
        "ffmpeg",
        "-y",
        "-loglevel",
        "error",
        "-i",
        str(raw_path),
        "-af",
        FFMPEG_FILTER,
        "-ac",
        "1",
        "-ar",
        "24000",
        "-b:a",
        "28k",
        str(out_path),
    ]
    res = subprocess.run(cmd, capture_output=True)
    return res.returncode == 0 and out_path.exists() and out_path.stat().st_size > 1024


async def synth_one(
    sem: asyncio.Semaphore,
    item_id: str,
    text_ko: str,
    out_path: Path,
    stats: dict[str, int],
) -> tuple[str, bool]:
    if out_path.exists() and out_path.stat().st_size > 2048:
        stats["skipped"] += 1
        return item_id, True

    async with sem:
        for attempt in range(4):
            raw_fd, raw_name = tempfile.mkstemp(suffix=".mp3")
            os.close(raw_fd)
            raw_path = Path(raw_name)
            try:
                comm = edge_tts.Communicate(
                    text_ko,
                    VOICE_ID,
                    rate=VOICE_RATE,
                    pitch=VOICE_PITCH,
                )
                await comm.save(str(raw_path))
                ok = await asyncio.to_thread(master_mp3, raw_path, out_path)
                if ok:
                    stats["generated"] += 1
                    return item_id, True
            except Exception as exc:
                if attempt == 3:
                    print(f"[WARN] Failed {item_id}: {exc}", file=sys.stderr)
                await asyncio.sleep(0.8 * (attempt + 1))
            finally:
                if raw_path.exists():
                    try:
                        raw_path.unlink()
                    except OSError:
                        pass
        stats["failed"] += 1
        return item_id, False


async def main() -> int:
    t0 = time.time()
    OUT_EX_DIR.mkdir(parents=True, exist_ok=True)
    OUT_CLIPS_DIR.mkdir(parents=True, exist_ok=True)

    payload = json.loads(SCRIPTS_JSON.read_text(encoding="utf-8"))
    exercises = payload["exercises"]
    clips = payload["clips"]

    sem = asyncio.Semaphore(CONCURRENCY)
    stats = {"generated": 0, "skipped": 0, "failed": 0}

    tasks = []
    for ex in exercises:
        out_path = OUT_EX_DIR / f"{ex['id']}.mp3"
        tasks.append(synth_one(sem, ex["id"], ex["textKo"], out_path, stats))

    for clip in clips:
        out_path = OUT_CLIPS_DIR / f"{clip['id']}.mp3"
        tasks.append(synth_one(sem, f"clip:{clip['id']}", clip["textKo"], out_path, stats))

    results = await asyncio.gather(*tasks)
    succeeded_ex = sorted(
        item_id for item_id, ok in results if ok and not item_id.startswith("clip:")
    )
    succeeded_clips = sorted(
        item_id.replace("clip:", "")
        for item_id, ok in results
        if ok and item_id.startswith("clip:")
    )

    total_bytes = sum(p.stat().st_size for p in OUT_EX_DIR.glob("*.mp3")) + sum(
        p.stat().st_size for p in OUT_CLIPS_DIR.glob("*.mp3")
    )

    manifest_lines = [
        "// Auto-generated by scripts/generate_studio_neural_voice.py — DO NOT EDIT BY HAND.",
        "// Studio Neural AI Voice pack mastered with Microsoft Azure Neural ko-KR-SunHiNeural (-16 LUFS).",
        "",
        "export const STUDIO_NEURAL_VOICE_MODEL = 'ko-KR-SunHiNeural' as const;",
        "export const STUDIO_NEURAL_VOICE_PERSONA_KO = '서연 · 스튜디오 AI 음성' as const;",
        "export const STUDIO_NEURAL_VOICE_BASE_URL = '/audio/studio-voice/ex' as const;",
        "export const STUDIO_NEURAL_CLIP_BASE_URL = '/audio/studio-voice/clips' as const;",
        "",
        f"export const STUDIO_NEURAL_EXERCISE_IDS: readonly string[] = {json.dumps(succeeded_ex, ensure_ascii=False, indent=2)};",
        "",
        "export const STUDIO_NEURAL_EXERCISE_ID_SET: ReadonlySet<string> = new Set(STUDIO_NEURAL_EXERCISE_IDS);",
        "",
        f"export const STUDIO_NEURAL_CLIP_IDS: readonly string[] = {json.dumps(succeeded_clips, ensure_ascii=False, indent=2)};",
        "",
        "export function getStudioNeuralExerciseAudioUrl(exerciseId: string | undefined | null): string | null {",
        "  if (!exerciseId) return null;",
        "  if (STUDIO_NEURAL_EXERCISE_ID_SET.has(exerciseId)) {",
        "    return `${STUDIO_NEURAL_VOICE_BASE_URL}/${exerciseId}.mp3`;",
        "  }",
        "  return null;",
        "}",
        "",
        "export function getStudioNeuralClipAudioUrl(clipId: string): string | null {",
        "  if (!STUDIO_NEURAL_CLIP_IDS.includes(clipId)) return null;",
        "  return `${STUDIO_NEURAL_CLIP_BASE_URL}/${clipId}.mp3`;",
        "}",
        "",
    ]
    MANIFEST_TS.write_text("\n".join(manifest_lines), encoding="utf-8")

    elapsed = time.time() - t0
    print(
        json.dumps(
            {
                "voiceId": VOICE_ID,
                "exercisesSucceeded": len(succeeded_ex),
                "clipsSucceeded": len(succeeded_clips),
                "generated": stats["generated"],
                "skipped": stats["skipped"],
                "failed": stats["failed"],
                "totalMB": round(total_bytes / (1024 * 1024), 2),
                "elapsedSec": round(elapsed, 1),
            },
            ensure_ascii=False,
        )
    )
    return 0 if stats["failed"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
